"""
事件（Incident）—— 把一堆告警收敛成一个"有主"的故障
============================================================
【为什么要有"事件"这一层】

告警是**现象**，事件是**一次故障**。

凌晨 3 点一次磁盘写满，可能同时打出 50 条告警：`DiskSpaceLow`、
`NginxHighErrorRate`、`NodeNotReady`、`PodCrashLooping`……
它们是**同一个故障**在不同角度上的投影。如果每一条都单独处理：

    - 值班的人会收到 50 条通知，然后学会无视通知（告警疲劳）
    - 模型会被调用 50 次，花 50 份钱，得出 50 个互相矛盾的结论
    - 复盘时没有任何一个地方能回答"这次故障是谁处理的"

所以这一层做两件事：**收敛（多个告警 → 一个事件）** 和 **归属（每一步都有主）**。
收敛键是 `host + service`（M2 的 I-3 负责算指纹，本模块负责记账）。

【目录结构与职责】

    model.py   状态机 + 等级归并 + 标识。**纯函数：不碰磁盘、不看时钟**
    store.py   持久化：追加 JSONL + 折叠；并发用 RLock

model 之所以坚持"纯函数"，是为了让**同一个判定被两个地方使用**：
接口层判"这个按钮能不能点"、存储层判"这次迁移合不合法"。
判定只有一份，就不会出现"UI 允许、后端拒绝"或者反过来的错位
（这和 sandbox 里 `policy` 只管判断、`executor` 只管执行的划分是同一条主线）。

【一个事件的完整一生】

    /webhook/alert 收到 50 条同源告警
      ↓ 聚合成 1 个事件
        created → alert_linked ×50（同一个 fingerprint 只算一条，计数 +1）
      ↓ 诊断完成
        attach_diagnosis（结论摘要 + trace_id；过不了校验的结论也要如实记 ok=False）
      ↓ 推通知
        mark_notified（送达与失败都记；**失败不许谎报成功**）
      ↓ 人：POST /incidents/{id}/ack      必须填 by —— 谁在处理
      ↓ 人：POST /incidents/{id}/resolve  必须填 by —— 谁结的单
      ↓ 同源告警又响了
        reopen（**复发必须记在同一个事件上**，否则"同一个故障反复发生"
        会被记成十次互不相干的故障，而"这东西老是坏"恰恰是最该被看见的信号）

【与审批单（approvals.py）的关系：同一套持久化，故意不同的终态语义】

两者都用"追加日志 + 折叠"，但终态的定义**故意不一样**：

    审批单的 consumed 是**绝对终态** —— 重放一次就是一次未授权变更，是漏洞；
    事件的 resolved 是**可被同源新告警推翻的** —— 故障会复发，这是现实。

把两者混为一谈，就会出两种事故：要么"故障复发了却没地方记"，
要么"一次授权被执行了两遍"。所以这里明确写成 `resolved --reopened-->` 一条边，
而不是简单地"终态不可逆"。

文档见 docs/redev/04-design-m2.md。
"""
